        #region Helpers

        private static string GetCategory(string menuPath)
        {
            if (string.IsNullOrEmpty(menuPath))
                return "Uncategorized";

            int slashIndex = menuPath.IndexOf('/');
            return slashIndex >= 0 ? menuPath.Substring(0, slashIndex) : menuPath;
        }

        /// <summary>
        /// Turns arbitrary text into something that can be part of an identifier. No keyword handling:
        /// the result is usually joined to other text first.
        /// </summary>
        private static string SanitizeIdentifierPart(string name)
        {
            if (string.IsNullOrEmpty(name))
                return "_unknown";

            var sb = new StringBuilder();

            // First character must be letter or underscore
            char first = name[0];
            if (!char.IsLetter(first) && first != '_')
                sb.Append('_');

            foreach (char c in name)
            {
                if (char.IsLetterOrDigit(c) || c == '_')
                    sb.Append(c);
                else
                    sb.Append('_');
            }

            return sb.ToString();
        }

        /// <summary>
        /// Prefixes a C# keyword with @ so it can be used as an identifier.
        /// </summary>
        private static string EscapeIdentifier(string identifier)
        {
            return ReservedKeywords.Contains(identifier) ? "@" + identifier : identifier;
        }

        private static string SingleLine(string text)
        {
            if (string.IsNullOrEmpty(text))
                return "";

            return text.Replace("\r\n", " ").Replace('\n', ' ').Replace('\r', ' ');
        }

        private static string EscapeXmlText(string text)
        {
            return SingleLine(text)
                .Replace("&", "&amp;")
                .Replace("<", "&lt;")
                .Replace(">", "&gt;");
        }

        /// <summary>
        /// The C# spelling of a type, valid from any namespace.
        /// </summary>
        internal static string GetTypeName(Type type)
        {
            return GetTypeName(type, false);
        }

        /// <param name="type">The type to name.</param>
        /// <param name="positionalGenerics">
        /// Name a method's type parameters by position instead of by name. Only for comparing signatures.
        /// </param>
        private static string GetTypeName(Type type, bool positionalGenerics)
        {
            if (type == null || type == typeof(void)) return "void";

            if (type.IsByRef)
                return GetTypeName(type.GetElementType(), positionalGenerics);

            if (type.IsArray)
            {
                // Rank specifiers read outermost first: an array of int[,] is int[][,]. Appending "[]" to
                // the element's own name, as the obvious recursion does, writes them the other way round.
                var ranks = new StringBuilder();
                Type element = type;

                while (element.IsArray)
                {
                    ranks.Append('[').Append(',', element.GetArrayRank() - 1).Append(']');
                    element = element.GetElementType();
                }

                return GetTypeName(element, positionalGenerics) + ranks;
            }

            if (type.IsGenericParameter)
            {
                return positionalGenerics && type.DeclaringMethod != null
                    ? "!!" + type.GenericParameterPosition
                    : EscapeIdentifier(type.Name);
            }

            if (type == typeof(int)) return "int";
            if (type == typeof(float)) return "float";
            if (type == typeof(bool)) return "bool";
            if (type == typeof(string)) return "string";
            if (type == typeof(double)) return "double";
            if (type == typeof(byte)) return "byte";
            if (type == typeof(sbyte)) return "sbyte";
            if (type == typeof(short)) return "short";
            if (type == typeof(ushort)) return "ushort";
            if (type == typeof(uint)) return "uint";
            if (type == typeof(long)) return "long";
            if (type == typeof(ulong)) return "ulong";
            if (type == typeof(char)) return "char";
            if (type == typeof(decimal)) return "decimal";
            if (type == typeof(object)) return "object";

            // Everything else is written from the root. The short name only resolves if the generated
            // file happens to import the right namespace, and Type.FullName is not C#: it spells a nested
            // type Outer+Inner and a generic one List`1[[...]].
            var chain = new List<Type>();
            for (Type current = type; current != null; current = current.DeclaringType)
            {
                chain.Insert(0, current);
            }

            Type[] genericArguments = type.IsGenericType ? type.GetGenericArguments() : Type.EmptyTypes;
            int writtenArguments = 0;

            var sb = new StringBuilder("global::");

            if (!string.IsNullOrEmpty(type.Namespace))
            {
                foreach (string part in type.Namespace.Split('.'))
                {
                    sb.Append(EscapeIdentifier(part)).Append('.');
                }
            }

            for (int i = 0; i < chain.Count; i++)
            {
                if (i > 0) sb.Append('.');

                Type link = chain[i];
                string name = link.Name;

                int arityMarker = name.IndexOf('`');
                if (arityMarker >= 0)
                    name = name.Substring(0, arityMarker);

                sb.Append(EscapeIdentifier(name));

                // A nested type reports its enclosing types' arguments along with its own, so each link
                // takes only the ones the links before it have not already used.
                int argumentsSoFar = link.IsGenericType ? link.GetGenericArguments().Length : 0;

                if (argumentsSoFar > writtenArguments && argumentsSoFar <= genericArguments.Length)
                {
                    sb.Append('<');

                    for (int a = writtenArguments; a < argumentsSoFar; a++)
                    {
                        if (a > writtenArguments) sb.Append(", ");
                        sb.Append(GetTypeName(genericArguments[a], positionalGenerics));
                    }

                    sb.Append('>');
                    writtenArguments = argumentsSoFar;
                }
            }

            return sb.ToString();
        }

        /// <summary>
        /// A short type name for text people read, such as the example usage. Not valid in generated code.
        /// </summary>
        private static string GetDisplayTypeName(Type type)
        {
            if (type == null) return "void";

            if (type == typeof(void)) return "void";
            if (type == typeof(int)) return "int";
            if (type == typeof(float)) return "float";
            if (type == typeof(bool)) return "bool";
            if (type == typeof(string)) return "string";
            if (type == typeof(double)) return "double";
            if (type == typeof(byte)) return "byte";
            if (type == typeof(sbyte)) return "sbyte";
            if (type == typeof(short)) return "short";
            if (type == typeof(ushort)) return "ushort";
            if (type == typeof(uint)) return "uint";
            if (type == typeof(long)) return "long";
            if (type == typeof(ulong)) return "ulong";
            if (type == typeof(char)) return "char";
            if (type == typeof(object)) return "object";

            if (type.IsArray)
            {
                return GetDisplayTypeName(type.GetElementType()) + "[]";
            }

            if (type.IsByRef)
            {
                return GetDisplayTypeName(type.GetElementType());
            }

            return type.Name;
        }

        private static string GetDefaultValueString(Type type)
        {
            if (type == typeof(int)) return "0";
            if (type == typeof(float)) return "0f";
            if (type == typeof(bool)) return "false";
            if (type == typeof(string)) return "\"\"";
            if (type == typeof(double)) return "0.0";
            if (type == typeof(byte)) return "0";
            if (type == typeof(Vector2)) return "Vector2.zero";
            if (type == typeof(Vector3)) return "Vector3.zero";
            if (type == typeof(Vector4)) return "Vector4.zero";
            if (type == typeof(Quaternion)) return "Quaternion.identity";
            if (type == typeof(Color)) return "Color.white";

            if (type.IsArray)
            {
                return "null";
            }

            if (type.IsValueType)
            {
                return $"default({GetDisplayTypeName(type)})";
            }

            return "null";
        }

