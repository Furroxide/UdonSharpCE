        #region Source Building

        /// <summary>
        /// One class to be generated: the nodes it wraps and how it describes itself.
        /// </summary>
        private sealed class WrapperClass
        {
            public string ClassName;
            public string HeaderLine;
            public string Summary;
            public readonly List<NodeDefinition> Nodes = new List<NodeDefinition>();
        }

        /// <summary>
        /// One method of a generated class, with the name it was given once collisions were settled.
        /// </summary>
        private sealed class WrapperMember
        {
            public NodeDefinition Node;
            public string Name;
        }

        /// <summary>
        /// Builds the per-category wrapper files, keyed by file name. Nothing is written to disk.
        /// </summary>
        /// <param name="nodes">The nodes to wrap.</param>
        /// <param name="warnings">Receives one line per node that was left out; may be null.</param>
        internal static Dictionary<string, string> BuildCategoryWrapperSources(
            IEnumerable<NodeDefinition> nodes,
            List<string> warnings)
        {
            var classes = new List<WrapperClass>();

            // Grouped by the class name the category turns into, ignoring case: "My Tools" and "My_Tools"
            // are one identifier, and "Math" and "math" are one file on most disks.
            var byClassName = new Dictionary<string, WrapperClass>(StringComparer.OrdinalIgnoreCase);

            foreach (var node in nodes)
            {
                if (node?.Method == null)
                    continue;

                string category = GetCategory(node.MenuPath);
                string className = SanitizeIdentifierPart(category) + CATEGORY_CLASS_SUFFIX;

                if (!byClassName.TryGetValue(className, out WrapperClass wrapperClass))
                {
                    wrapperClass = new WrapperClass
                    {
                        ClassName = className,
                        HeaderLine = $"// Category: {SingleLine(category)}",
                        Summary = $"Generated wrapper methods for {category} graph nodes."
                    };

                    byClassName.Add(className, wrapperClass);
                    classes.Add(wrapperClass);
                }

                wrapperClass.Nodes.Add(node);
            }

            return GenerateSources(classes, warnings);
        }

        /// <summary>
        /// Builds the per-node wrapper files, keyed by file name: one class for each wrapped method name
        /// on each containing type, holding every overload. Nothing is written to disk.
        /// </summary>
        /// <param name="nodes">The nodes to wrap.</param>
        /// <param name="warnings">Receives one line per node that was left out; may be null.</param>
        internal static Dictionary<string, string> BuildNodeWrapperSources(
            IEnumerable<NodeDefinition> nodes,
            List<string> warnings)
        {
            var classes = new List<WrapperClass>();
            var byClassName = new Dictionary<string, WrapperClass>(StringComparer.OrdinalIgnoreCase);

            foreach (var node in nodes)
            {
                if (node?.Method == null)
                    continue;

                string className = GetNodeWrapperClassName(node);

                if (!byClassName.TryGetValue(className, out WrapperClass wrapperClass))
                {
                    wrapperClass = new WrapperClass
                    {
                        ClassName = className,
                        HeaderLine = $"// Node: {SingleLine(node.MenuPath)}",
                        Summary = $"Generated wrapper for {node.MenuPath}."
                    };

                    byClassName.Add(className, wrapperClass);
                    classes.Add(wrapperClass);
                }

                wrapperClass.Nodes.Add(node);
            }

            return GenerateSources(classes, warnings);
        }

        private static Dictionary<string, string> GenerateSources(List<WrapperClass> classes, List<string> warnings)
        {
            var sources = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);

            foreach (var wrapperClass in classes)
            {
                string code = GenerateWrapperClass(wrapperClass, warnings);

                // Null when every node in the class had to be skipped. No file, rather than an empty class.
                if (code != null)
                {
                    sources[wrapperClass.ClassName + ".cs"] = code;
                }
            }

            return sources;
        }

        /// <summary>
        /// The class a node's own wrapper lives in. Built from the containing type as well as the method,
        /// so that Math.Add and Vector.Add do not both ask for a class called AddWrapper.
        /// </summary>
        private static string GetNodeWrapperClassName(NodeDefinition node)
        {
            Type containingType = node.ContainingType ?? node.Method.DeclaringType;
            string typePart = SanitizeIdentifierPart(containingType?.FullName ?? containingType?.Name ?? "Unknown");

            return typePart + "_" + SanitizeIdentifierPart(GetWrapperMethodName(node.Method)) + NODE_CLASS_SUFFIX;
        }

        #endregion

        #region Code Generation

        private static string GenerateWrapperClass(WrapperClass wrapperClass, List<string> warnings)
        {
            List<WrapperMember> members = PlanMembers(wrapperClass.Nodes, warnings);
            if (members.Count == 0)
                return null;

            var sb = new StringBuilder();

            // Header. No timestamp: it changed on every run, so every run rewrote every file and forced a
            // recompile of the whole project to say nothing new.
            sb.AppendLine("// =============================================================================");
            sb.AppendLine(HEADER_MARKER);
            sb.AppendLine(HEADER_GENERATOR);
            sb.AppendLine(wrapperClass.HeaderLine);
            sb.AppendLine("// =============================================================================");
            sb.AppendLine();

            // No using directives. Every type below is written out in full from global::, so nothing in
            // this file depends on what a using would bring into scope -- or on what the user has named
            // their own types.

            // Namespace
            sb.AppendLine($"namespace {NAMESPACE}");
            sb.AppendLine("{");

            // Class
            sb.AppendLine($"    /// <summary>");
            sb.AppendLine($"    /// {EscapeXmlText(wrapperClass.Summary)}");
            sb.AppendLine($"    /// </summary>");
            sb.AppendLine($"    public static class {wrapperClass.ClassName}");
            sb.AppendLine("    {");

            // Generate methods
            foreach (var member in members)
            {
                sb.AppendLine();
                GenerateMethod(sb, member);
            }

            sb.AppendLine("    }");
            sb.AppendLine("}");

            return sb.ToString();
        }

        /// <summary>
        /// Decides which nodes become methods of a class, and under what name.
        /// </summary>
        private static List<WrapperMember> PlanMembers(List<NodeDefinition> nodes, List<string> warnings)
        {
            var members = new List<WrapperMember>();
            var seenMethods = new HashSet<string>();
            var usedSignatures = new HashSet<string>();

            foreach (var node in nodes)
            {
                MethodInfo method = node.Method;

                // The same method listed twice is one wrapper. Reflection returns an inherited instance
                // method again for every subclass, each time as a different MethodInfo object, so this
                // compares the metadata identity rather than the reference.
                if (!seenMethods.Add(method.Module.ModuleVersionId + ":" + method.MetadataToken))
                    continue;

                string unsupportedReason = GetUnsupportedReason(method);
                if (unsupportedReason != null)
                {
                    warnings?.Add($"Skipped {DescribeNode(node)}: {unsupportedReason}.");
                    continue;
                }

                // Two different methods can still ask for the same name and parameter list -- Open() on
                // two behaviours filed under one category, say. The later one takes its type's name as a
                // prefix instead of being emitted as a duplicate member.
                Type containingType = node.ContainingType ?? method.DeclaringType;
                string baseName = SanitizeIdentifierPart(GetWrapperMethodName(method));
                string parameterKey = GetParameterKey(method);

                string[] candidates =
                {
                    baseName,
                    SanitizeIdentifierPart(containingType.Name) + "_" + baseName,
                    SanitizeIdentifierPart(containingType.FullName ?? containingType.Name) + "_" + baseName
                };

                string chosenName = null;

                foreach (string candidate in candidates)
                {
                    if (usedSignatures.Add(candidate + parameterKey))
                    {
                        chosenName = candidate;
                        break;
                    }
                }

                if (chosenName == null)
                {
                    warnings?.Add($"Skipped {DescribeNode(node)}: another node already uses every name it could be given.");
                    continue;
                }

                members.Add(new WrapperMember { Node = node, Name = chosenName });
            }

            return members;
        }

        /// <summary>
        /// Why a method cannot be wrapped, or null if it can. A node that would need code this generator
        /// cannot write correctly is left out and reported; emitting a near miss breaks the build.
        /// </summary>
        private static string GetUnsupportedReason(MethodInfo method)
        {
            Type declaringType = method.DeclaringType;

            if (declaringType == null)
                return "it has no declaring type";

            if (declaringType.ContainsGenericParameters)
                return $"{declaringType.Name} is an open generic type";

            if (!method.IsPublic || !declaringType.IsVisible)
                return "it is not reachable from generated code (the method and every type around it must be public)";

            if (method.IsGenericMethodDefinition && HasGenericConstraints(method))
                return "its type parameters carry constraints, which are not reproduced";

            if (method.ReturnType.IsByRef)
                return "it returns by reference";

            if (!IsExpressibleType(method.ReturnType))
                return $"its return type {method.ReturnType.Name} is not public or cannot be named";

            ParameterInfo[] parameters = method.GetParameters();

            foreach (ParameterInfo parameter in parameters)
            {
                if (!IsExpressibleType(parameter.ParameterType))
                    return $"parameter '{parameter.Name}' has type {parameter.ParameterType.Name}, which is not public or cannot be named";
            }

            if (method.IsSpecialName)
            {
                if (!IsPropertyAccessor(method))
                    return "it is an operator or other special member";

                // A static accessor is emitted as a property read or write, which only has a spelling for
                // the plain forms.
                if (method.IsStatic && parameters.Length != (IsPropertyGetter(method) ? 0 : 1))
                    return "it is an accessor of an indexed property";
            }

            string hiddenAssembly = FindAssemblyHiddenFromWrappers(method);
            if (hiddenAssembly != null)
            {
                return $"it uses {hiddenAssembly}, which the wrappers cannot reference: they compile into " +
                       "Assembly-CSharp, which sees only auto-referenced, non-editor assemblies";
            }

            return null;
        }

        // Script assemblies the generated files can reference, and every script assembly there is. Both
        // null when the compilation pipeline could not be asked, which turns the check off.
        private static HashSet<string> _scriptAssembliesVisibleToWrappers;
        private static HashSet<string> _allScriptAssemblies;
        private static bool _wrapperVisibilityResolved;

        /// <summary>
        /// The first assembly a wrapper for <paramref name="method"/> would need and cannot reference, or
        /// null.
        ///
        /// The wrappers are written under Assets/ with no assembly definition, so they compile into
        /// Assembly-CSharp. A node declared in an editor-only assembly, a test assembly, or an assembly
        /// definition with Auto Referenced turned off -- or one whose signature uses a type from one --
        /// produced a wrapper naming a type Assembly-CSharp cannot see, and that file stopped the whole
        /// project compiling.
        /// </summary>
        private static string FindAssemblyHiddenFromWrappers(MethodInfo method)
        {
            ResolveWrapperVisibility();

            if (_scriptAssembliesVisibleToWrappers == null)
                return null;

            var types = new List<Type> { method.DeclaringType, method.ReturnType };
            types.AddRange(method.GetParameters().Select(parameter => parameter.ParameterType));

            if (method.IsGenericMethod)
                types.AddRange(method.GetGenericArguments());

            foreach (Type type in types)
            {
                string hidden = FindAssemblyHiddenFromWrappers(type);
                if (hidden != null)
                    return hidden;
            }

            return null;
        }

        private static string FindAssemblyHiddenFromWrappers(Type type)
        {
            while (type.HasElementType)
            {
                type = type.GetElementType();
            }

            if (type.IsGenericParameter)
                return null;

            string assemblyName = type.Assembly.GetName().Name;

            // Only script assemblies are judged. Engine, framework and precompiled plugin assemblies reach
            // Assembly-CSharp through compiler defaults the pipeline does not list per assembly, and
            // refusing them would refuse every node that takes a Vector3.
            if (_allScriptAssemblies.Contains(assemblyName) && !_scriptAssembliesVisibleToWrappers.Contains(assemblyName))
                return assemblyName;

            if (type.IsGenericType)
            {
                foreach (Type argument in type.GetGenericArguments())
                {
                    string hidden = FindAssemblyHiddenFromWrappers(argument);
                    if (hidden != null)
                        return hidden;
                }
            }

            return null;
        }

        private static void ResolveWrapperVisibility()
        {
            if (_wrapperVisibilityResolved)
                return;

            _wrapperVisibilityResolved = true;

            try
            {
                var allScriptAssemblies = new HashSet<string>(
                    CompilationPipeline.GetAssemblies(AssembliesType.Editor).Select(assembly => assembly.name),
                    StringComparer.Ordinal);

                UnityEditor.Compilation.Assembly[] playerAssemblies =
                    CompilationPipeline.GetAssemblies(AssembliesType.PlayerWithoutTestAssemblies);

                UnityEditor.Compilation.Assembly assemblyCSharp =
                    playerAssemblies.FirstOrDefault(assembly => assembly.name == "Assembly-CSharp");

                HashSet<string> visible;

                if (assemblyCSharp != null)
                {
                    visible = new HashSet<string>(assemblyCSharp.assemblyReferences.Select(assembly => assembly.name), StringComparer.Ordinal)
                    {
                        assemblyCSharp.name
                    };
                }
                else
                {
                    // No loose scripts yet, so no Assembly-CSharp to ask. It will see at most the player
                    // assemblies; whether each one is auto-referenced cannot be told from here.
                    visible = new HashSet<string>(playerAssemblies.Select(assembly => assembly.name), StringComparer.Ordinal)
                    {
                        "Assembly-CSharp"
                    };
                }

                _allScriptAssemblies = allScriptAssemblies;
                _scriptAssembliesVisibleToWrappers = visible;
            }
            catch (Exception ex)
            {
                // Without an answer nothing is filtered here; the parse check before writing still applies.
                Debug.LogWarning($"[GraphNodeCodeGenerator] Could not read the script assembly layout, so wrappers are not checked for unreachable assemblies: {ex.Message}");
                _allScriptAssemblies = null;
                _scriptAssembliesVisibleToWrappers = null;
            }
        }

        private static bool HasGenericConstraints(MethodInfo method)
        {
            foreach (Type argument in method.GetGenericArguments())
            {
                if ((argument.GenericParameterAttributes & GenericParameterAttributes.SpecialConstraintMask) != GenericParameterAttributes.None)
                    return true;

                if (argument.GetGenericParameterConstraints().Length > 0)
                    return true;
            }

            return false;
        }

        private static bool IsExpressibleType(Type type)
        {
            while (type.HasElementType)
            {
                if (type.IsPointer)
                    return false;

                type = type.GetElementType();
            }

            if (type.IsGenericParameter)
                return true;

            // Public, with every enclosing type and every type argument public too.
            return type.IsVisible;
        }

        private static bool IsPropertyAccessor(MethodInfo method)
        {
            return method.IsSpecialName &&
                   (method.Name.StartsWith("get_", StringComparison.Ordinal) ||
                    method.Name.StartsWith("set_", StringComparison.Ordinal)) &&
                   method.Name.Length > 4;
        }

        private static bool IsPropertyGetter(MethodInfo method)
        {
            return method.Name.StartsWith("get_", StringComparison.Ordinal);
        }

        /// <summary>
        /// The name a wrapper is given before collisions are settled. A property accessor is called
        /// get_Health in metadata, which cannot be invoked by that name from C#, so it becomes GetHealth.
        /// </summary>
        private static string GetWrapperMethodName(MethodInfo method)
        {
            if (IsPropertyAccessor(method))
                return (IsPropertyGetter(method) ? "Get" : "Set") + method.Name.Substring(4);

            return method.Name;
        }

        /// <summary>
        /// The part of a signature that decides whether two methods of one name can coexist: arity and
        /// parameter types. ref, out and in all count as the same thing, as they do to the compiler, and
        /// a method's own type parameters are compared by position, not by what they were called.
        /// </summary>
        private static string GetParameterKey(MethodInfo method)
        {
            var sb = new StringBuilder();

            if (method.IsGenericMethodDefinition)
            {
                sb.Append('`').Append(method.GetGenericArguments().Length);
            }

            sb.Append('(');

            ParameterInfo[] parameters = method.GetParameters();
            for (int i = 0; i < parameters.Length; i++)
            {
                if (i > 0) sb.Append(',');

                if (parameters[i].ParameterType.IsByRef)
                    sb.Append('&');

                sb.Append(GetTypeName(parameters[i].ParameterType, true));
            }

            sb.Append(')');

            return sb.ToString();
        }

        private static string DescribeNode(NodeDefinition node)
        {
            Type containingType = node.ContainingType ?? node.Method.DeclaringType;
            return $"'{node.MenuPath}' ({containingType?.FullName ?? "?"}.{node.Method.Name})";
        }

        private static void GenerateMethod(StringBuilder sb, WrapperMember member)
        {
            NodeDefinition node = member.Node;
            MethodInfo method = node.Method;
            ParameterInfo[] parameters = method.GetParameters();
            string[] parameterNames = GetParameterNames(parameters);

            // XML Documentation. Escaped and kept to one line: a tooltip is free text, and a line break in
            // it used to end the comment and leave the rest of the sentence as code.
            sb.AppendLine($"        /// <summary>");
            sb.AppendLine($"        /// {EscapeXmlText(node.Tooltip ?? node.MenuPath)}");
            sb.AppendLine($"        /// </summary>");

            // Document parameters
            for (int i = 0; i < parameters.Length; i++)
            {
                sb.AppendLine($"        /// <param name=\"{parameterNames[i]}\">{EscapeXmlText(DescribeParameter(parameters[i]))}</param>");
            }

            // Document return
            if (method.ReturnType != typeof(void))
            {
                sb.AppendLine($"        /// <returns>The result of the operation.</returns>");
            }

            // Method signature
            string genericParameters = GetGenericParameterList(method);

            sb.Append($"        public static {GetTypeName(method.ReturnType)} {EscapeIdentifier(member.Name)}{genericParameters}(");

            // Parameters
            for (int i = 0; i < parameters.Length; i++)
            {
                if (i > 0) sb.Append(", ");

                sb.Append(GetParameterModifier(parameters[i]));
                sb.Append($"{GetTypeName(parameters[i].ParameterType)} {EscapeIdentifier(parameterNames[i])}");
            }

            sb.AppendLine(")");
            sb.AppendLine("        {");

            // Method body - call the original method
            if (method.IsStatic)
            {
                GenerateStaticMethodCall(sb, node, parameters, parameterNames, genericParameters);
            }
            else
            {
                // For instance methods, we need to note they require a reference
                sb.AppendLine($"            // NOTE: This is an instance method from {SingleLine(node.ContainingType?.Name)}.");
                sb.AppendLine($"            // You need a reference to the containing behaviour to call this method.");
                sb.AppendLine($"            throw new global::System.NotImplementedException(\"Instance method - requires behaviour reference\");");
            }

            sb.AppendLine("        }");
        }

        private static void GenerateStaticMethodCall(
            StringBuilder sb,
            NodeDefinition node,
            ParameterInfo[] parameters,
            string[] parameterNames,
            string genericParameters)
        {
            MethodInfo method = node.Method;

            // From global::, always. A bare type name is looked up from inside the generated namespace
            // first, and anything of that name there -- the generated class itself, for one -- wins.
            string target = GetTypeName(node.ContainingType ?? method.DeclaringType);

            sb.Append("            ");

            if (IsPropertyAccessor(method))
            {
                // An accessor cannot be called as a method (CS0571); it is a read or a write.
                string propertyName = EscapeIdentifier(method.Name.Substring(4));

                if (IsPropertyGetter(method))
                    sb.AppendLine($"return {target}.{propertyName};");
                else
                    sb.AppendLine($"{target}.{propertyName} = {EscapeIdentifier(parameterNames[0])};");

                return;
            }

            if (method.ReturnType != typeof(void))
            {
                sb.Append("return ");
            }

            sb.Append($"{target}.{EscapeIdentifier(method.Name)}{genericParameters}(");

            for (int i = 0; i < parameters.Length; i++)
            {
                if (i > 0) sb.Append(", ");

                sb.Append(GetParameterModifier(parameters[i]));
                sb.Append(EscapeIdentifier(parameterNames[i]));
            }

            sb.AppendLine(");");
        }

        /// <summary>
        /// "&lt;T, U&gt;" for a generic method, or nothing. The same text declares the wrapper's type
        /// parameters and passes them on to the wrapped method.
        /// </summary>
        private static string GetGenericParameterList(MethodInfo method)
        {
            if (!method.IsGenericMethodDefinition)
                return "";

            return "<" + string.Join(", ", method.GetGenericArguments().Select(argument => EscapeIdentifier(argument.Name))) + ">";
        }

        private static string GetParameterModifier(ParameterInfo parameter)
        {
            if (!parameter.ParameterType.IsByRef)
                return "";

            if (parameter.IsOut)
                return "out ";

            // 'in' has to be told apart from 'ref': both are by-reference, and passing 'ref' to an 'in'
            // parameter does not compile.
            if (parameter.IsIn && parameter.GetCustomAttributesData().Any(
                    data => data.AttributeType.FullName == "System.Runtime.CompilerServices.IsReadOnlyAttribute"))
            {
                return "in ";
            }

            return "ref ";
        }

        /// <summary>
        /// Identifier-safe parameter names, unique within the method and without the @ a keyword needs.
        /// </summary>
        private static string[] GetParameterNames(ParameterInfo[] parameters)
        {
            var names = new string[parameters.Length];
            var used = new HashSet<string>();

            for (int i = 0; i < parameters.Length; i++)
            {
                string name = string.IsNullOrEmpty(parameters[i].Name)
                    ? "arg" + i
                    : SanitizeIdentifierPart(parameters[i].Name);

                while (!used.Add(name))
                {
                    name += "_" + i;
                }

                names[i] = name;
            }

            return names;
        }

        private static string DescribeParameter(ParameterInfo parameter)
        {
            var inputAttribute = parameter.GetCustomAttribute<GraphInputAttribute>();
            var outputAttribute = parameter.GetCustomAttribute<GraphOutputAttribute>();

            string tooltip = inputAttribute?.Tooltip ?? outputAttribute?.Tooltip;
            if (!string.IsNullOrEmpty(tooltip))
                return tooltip;

            bool isOutput = parameter.IsOut || outputAttribute != null;
            string displayName = inputAttribute?.DisplayName ?? outputAttribute?.DisplayName ?? parameter.Name;

            return (isOutput ? "Output: " : "Input: ") + displayName;
        }

