        #region File Output

        /// <summary>
        /// What one pass of <see cref="SyncGeneratedFiles"/> did to a folder.
        /// </summary>
        internal sealed class SyncResult
        {
            /// <summary>Files written because they were new or their text changed.</summary>
            public int Written => WrittenPaths.Count;

            public readonly List<string> WrittenPaths = new List<string>();

            /// <summary>Files whose text on disk was already exactly what was generated.</summary>
            public int Unchanged;

            /// <summary>Generated files deleted because nothing wants them any more.</summary>
            public readonly List<string> Removed = new List<string>();

            /// <summary>Files not written because the generated text does not parse, with the reason.</summary>
            public readonly List<string> Refused = new List<string>();

            /// <summary>Paths left alone because a file there was not written by this generator.</summary>
            public readonly List<string> Foreign = new List<string>();
        }

        private static string GetOutputPath(string folder, string fileName)
        {
            return folder + "/" + fileName;
        }

        private static bool IsAssetPath(string path)
        {
            return path.Replace(Path.DirectorySeparatorChar, '/').StartsWith("Assets/", StringComparison.Ordinal);
        }

        /// <summary>
        /// Writes generated files into <paramref name="folder"/> and, when <paramref name="removeStale"/> is
        /// set, deletes the files this generator wrote there earlier that <paramref name="sources"/> no
        /// longer contains. Reports instead of logging, so the caller decides what is worth a message.
        /// </summary>
        internal static SyncResult SyncGeneratedFiles(string folder, IReadOnlyDictionary<string, string> sources, bool removeStale)
        {
            var result = new SyncResult();

            if (sources.Count > 0)
            {
                EnsureFolder(folder);
            }

            foreach (var source in sources)
            {
                string path = GetOutputPath(folder, source.Key);

                // Last line of defence. A file with a syntax error in Assets/ stops the project compiling,
                // and with it the only thing that could regenerate the file.
                if (HasSyntaxErrors(source.Value, out string syntaxError))
                {
                    result.Refused.Add($"{path}: {syntaxError}");
                    continue;
                }

                if (File.Exists(path))
                {
                    if (!IsGeneratedFile(path))
                    {
                        result.Foreign.Add(path);
                        continue;
                    }

                    // Unchanged text is not rewritten, so regenerating does not touch the file, does not
                    // trigger a recompile and does not show up as a change in version control.
                    if (NormalizeLineEndings(File.ReadAllText(path)) == NormalizeLineEndings(source.Value))
                    {
                        result.Unchanged++;
                        continue;
                    }
                }

                File.WriteAllText(path, source.Value);
                result.WrittenPaths.Add(path);
            }

            if (removeStale)
            {
                DeleteStaleFiles(folder, sources.Keys, result);
            }

            return result;
        }

        private static void LogSyncResult(SyncResult result)
        {
            foreach (string refusal in result.Refused)
            {
                Debug.LogError($"[GraphNodeCodeGenerator] Not writing {refusal}. The generated code does not parse; " +
                               "this is a generator bug, and the file on disk, if any, was left as it was.");
            }

            foreach (string path in result.Foreign)
            {
                Debug.LogWarning($"[GraphNodeCodeGenerator] {path} already exists and was not written by this generator. It was left alone.");
            }

            foreach (string path in result.Removed)
            {
                Debug.Log($"[GraphNodeCodeGenerator] Removed stale wrapper {path}");
            }
        }

        private static void EnsureFolder(string folder)
        {
            if (!IsAssetPath(folder))
            {
                Directory.CreateDirectory(folder);
                return;
            }

            EnsureAssetFolder(folder);
        }

        private static void EnsureAssetFolder(string folder)
        {
            // Through the asset database, one level at a time, so each new folder gets its .meta.
            string[] parts = folder.Replace(Path.DirectorySeparatorChar, '/').TrimEnd('/').Split('/');
            string current = parts[0];

            for (int i = 1; i < parts.Length; i++)
            {
                string next = current + "/" + parts[i];

                if (!AssetDatabase.IsValidFolder(next))
                {
                    AssetDatabase.CreateFolder(current, parts[i]);
                }

                current = next;
            }
        }

        /// <summary>
        /// Removes generated files that are no longer wanted. Only files carrying this generator's header
        /// are ever candidates; anything else in the folder is the user's.
        /// </summary>
        private static void DeleteStaleFiles(string folder, IEnumerable<string> wantedFileNames, SyncResult result)
        {
            if (!Directory.Exists(folder))
                return;

            var wanted = new HashSet<string>(wantedFileNames, StringComparer.OrdinalIgnoreCase);

            foreach (string file in Directory.GetFiles(folder, "*.cs", SearchOption.TopDirectoryOnly))
            {
                string fileName = Path.GetFileName(file);

                if (wanted.Contains(fileName) || !IsGeneratedFile(file))
                    continue;

                string path = GetOutputPath(folder, fileName);

                // Through the asset database where there is one, which takes the .meta with it. A file it
                // does not know -- not imported yet, or outside Assets/ -- is deleted directly.
                if (!IsAssetPath(path) || !DeleteAsset(path))
                {
                    File.Delete(file);

                    if (File.Exists(file + ".meta"))
                        File.Delete(file + ".meta");
                }

                result.Removed.Add(path);
            }
        }

        private static bool DeleteAsset(string assetPath)
        {
            return AssetDatabase.DeleteAsset(assetPath);
        }

        /// <summary>
        /// Whether a file starts with this generator's header.
        /// </summary>
        private static bool IsGeneratedFile(string path)
        {
            if (!File.Exists(path))
                return false;

            bool sawMarker = false;
            bool sawGenerator = false;

            using (var reader = new StreamReader(path))
            {
                for (int i = 0; i < 4; i++)
                {
                    string line = reader.ReadLine();
                    if (line == null)
                        break;

                    line = line.Trim();

                    if (line == HEADER_MARKER) sawMarker = true;
                    if (line == HEADER_GENERATOR) sawGenerator = true;
                }
            }

            return sawMarker && sawGenerator;
        }

        /// <summary>
        /// Whether generated text fails to parse as C#. Syntax only -- it cannot tell that a name does not
        /// resolve -- but it is cheap, needs no references, and catches a malformed file before it is
        /// written. Parsed at the language version Unity compiles the file with, so syntax this Roslyn
        /// knows and Unity's compiler does not still counts as an error.
        /// </summary>
        internal static bool HasSyntaxErrors(string code, out string firstError)
        {
            firstError = null;

#if UNITY_2022_3_OR_NEWER
            const Microsoft.CodeAnalysis.CSharp.LanguageVersion languageVersion = Microsoft.CodeAnalysis.CSharp.LanguageVersion.CSharp9;
#else
            const Microsoft.CodeAnalysis.CSharp.LanguageVersion languageVersion = Microsoft.CodeAnalysis.CSharp.LanguageVersion.CSharp7_3;
#endif

            var tree = Microsoft.CodeAnalysis.CSharp.CSharpSyntaxTree.ParseText(
                code,
                Microsoft.CodeAnalysis.CSharp.CSharpParseOptions.Default.WithLanguageVersion(languageVersion));

            foreach (var diagnostic in tree.GetDiagnostics())
            {
                if (diagnostic.Severity == Microsoft.CodeAnalysis.DiagnosticSeverity.Error)
                {
                    firstError = diagnostic.ToString();
                    return true;
                }
            }

            return false;
        }

        private static string NormalizeLineEndings(string text)
        {
            return text.Replace("\r\n", "\n");
        }

