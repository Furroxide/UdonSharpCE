    /// <summary>
    /// Generates UdonSharp wrapper code from [GraphNode] decorated methods.
    /// Creates type-safe, Udon-compatible wrapper classes that can be used in UdonSharpBehaviours.
    /// </summary>
    /// <remarks>
    /// The output lands under Assets/ and is compiled with the rest of the project, so one file that does
    /// not compile stops every script from compiling -- including this generator, which reads its nodes
    /// from the last assembly that did build and so regenerates the same file. Everything here that
    /// looks defensive is there for that reason: names are written fully qualified, anything that cannot
    /// be expressed is skipped with a warning rather than emitted approximately, and nothing is written
    /// to disk until it has been parsed.
    /// </remarks>
    public static class GraphNodeCodeGenerator
    {
        #region Constants

        private const string OUTPUT_FOLDER = "Assets/UdonSharpCE/GeneratedWrappers";
        private const string NAMESPACE = "UdonSharp.CE.Generated";

        // The two header lines every file written here carries. They are how a file is recognised as
        // this generator's own before it is overwritten or deleted.
        private const string HEADER_MARKER = "// AUTO-GENERATED CODE - DO NOT MODIFY";
        private const string HEADER_GENERATOR = "// Generated by UdonSharpCE GraphNodeCodeGenerator";

        // Class name suffixes. Not "Nodes": the documentation's own example keeps its [GraphNode] methods
        // in a class called MathNodes under the menu path "Math/...", and a generated class of the same
        // name in this namespace is what an unqualified "MathNodes.Lerp(...)" in its body resolved to --
        // the wrapper called itself until the stack ran out.
        private const string CATEGORY_CLASS_SUFFIX = "GraphWrappers";
        private const string NODE_CLASS_SUFFIX = "Wrapper";

        private static readonly HashSet<string> ReservedKeywords = new HashSet<string>
        {
            "abstract", "as", "base", "bool", "break", "byte", "case", "catch",
            "char", "checked", "class", "const", "continue", "decimal", "default",
            "delegate", "do", "double", "else", "enum", "event", "explicit",
            "extern", "false", "finally", "fixed", "float", "for", "foreach",
            "goto", "if", "implicit", "in", "int", "interface", "internal",
            "is", "lock", "long", "namespace", "new", "null", "object", "operator",
            "out", "override", "params", "private", "protected", "public",
            "readonly", "ref", "return", "sbyte", "sealed", "short", "sizeof",
            "stackalloc", "static", "string", "struct", "switch", "this", "throw",
            "true", "try", "typeof", "uint", "ulong", "unchecked", "unsafe",
            "ushort", "using", "virtual", "void", "volatile", "while"
        };

        #endregion

        #region Public Methods

        /// <summary>
        /// Generates wrapper code for all discovered graph nodes.
        /// </summary>
        [MenuItem("Udon CE/Graph Bridge/Generate Wrappers", false, 1504)]
        public static void GenerateAllWrappers()
        {
            var nodes = GraphNodeGenerator.GetNodeDefinitions();
            var warnings = new List<string>();

            Dictionary<string, string> sources = BuildCategoryWrapperSources(nodes, warnings);

            // Per-node wrappers are written one at a time from the node browser. The ones already on disk
            // are brought up to date here so a changed signature cannot leave one behind that no longer
            // compiles, without creating any the user never asked for.
            foreach (var nodeSource in BuildNodeWrapperSources(nodes, null))
            {
                if (IsGeneratedFile(GetOutputPath(OUTPUT_FOLDER, nodeSource.Key)))
                {
                    sources[nodeSource.Key] = nodeSource.Value;
                }
            }

            foreach (string warning in warnings)
            {
                Debug.LogWarning($"[GraphNodeCodeGenerator] {warning}");
            }

            // A wrapper whose category or node is gone still calls methods that may be gone too, so the
            // files this generator wrote and no longer wants go in the same pass.
            SyncResult result = SyncGeneratedFiles(OUTPUT_FOLDER, sources, true);
            LogSyncResult(result);

            if (result.Written > 0 || result.Removed.Count > 0)
            {
                AssetDatabase.Refresh();
            }

            if (sources.Count == 0 && result.Removed.Count == 0)
            {
                Debug.Log("[GraphNodeCodeGenerator] No graph nodes found to generate wrappers for.");
                return;
            }

            Debug.Log($"[GraphNodeCodeGenerator] {sources.Count} wrapper files for {nodes.Count} nodes in {OUTPUT_FOLDER} " +
                      $"({result.Written} written, {result.Removed.Count} stale removed)");
        }

        /// <summary>
        /// Generates a wrapper for a single node.
        /// </summary>
        public static void GenerateWrapper(NodeDefinition node)
        {
            if (node?.Method == null)
            {
                Debug.LogWarning("[GraphNodeCodeGenerator] Cannot generate wrapper for null node or node without method.");
                return;
            }

            // Every overload of the method goes into the one wrapper class. Writing a class per node gave
            // two overloads -- or two unrelated methods that happened to share a name -- the same class
            // name in the same namespace, and the second file broke the build.
            string className = GetNodeWrapperClassName(node);
            var group = GraphNodeGenerator.GetNodeDefinitions()
                .Where(other => other?.Method != null &&
                                string.Equals(GetNodeWrapperClassName(other), className, StringComparison.OrdinalIgnoreCase))
                .ToList();
            group.Add(node);

            var warnings = new List<string>();
            Dictionary<string, string> sources = BuildNodeWrapperSources(group, warnings);

            foreach (string warning in warnings)
            {
                Debug.LogWarning($"[GraphNodeCodeGenerator] {warning}");
            }

            if (sources.Count == 0)
            {
                Debug.LogWarning($"[GraphNodeCodeGenerator] No wrapper could be generated for {node.MenuPath}.");
                return;
            }

            SyncResult result = SyncGeneratedFiles(OUTPUT_FOLDER, sources, false);
            LogSyncResult(result);

            foreach (string path in result.WrittenPaths)
            {
                Debug.Log($"[GraphNodeCodeGenerator] Generated wrapper at {path}");
            }

            if (result.Written > 0)
            {
                AssetDatabase.Refresh();
            }
        }

        /// <summary>
        /// Generates example usage code for a node.
        /// </summary>
        public static string GenerateExampleUsage(NodeDefinition node)
        {
            if (node?.Method == null)
                return "// No method available";

            var sb = new StringBuilder();

            sb.AppendLine("// Example usage:");

            // Build the call
            if (node.Method.ReturnType != typeof(void))
            {
                sb.Append($"{GetDisplayTypeName(node.Method.ReturnType)} result = ");
            }

            if (node.Method.IsStatic)
            {
                sb.Append($"{node.ContainingType?.Name ?? "Unknown"}.");
            }
            else
            {
                sb.Append("instance.");
            }

            sb.Append($"{node.Method.Name}(");

            var parameters = node.Method.GetParameters()
                .Where(p => !p.IsOut)
                .ToList();

            for (int i = 0; i < parameters.Count; i++)
            {
                if (i > 0) sb.Append(", ");
                sb.Append(GetDefaultValueString(parameters[i].ParameterType));
            }

            sb.AppendLine(");");

            return sb.ToString();
        }

